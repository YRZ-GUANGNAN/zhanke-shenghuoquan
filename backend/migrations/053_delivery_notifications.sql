-- Additive notification metadata only. Re-running creates no historical tasks.
-- Private chat text and provider credentials must never enter these tables.
CREATE TABLE IF NOT EXISTS delivery_notification_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  event_public_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  event_type VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  aggregate_type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  aggregate_public_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
  aggregate_version BIGINT UNSIGNED NOT NULL,
  payload_version INT UNSIGNED NOT NULL DEFAULT 1,
  payload JSON NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'pending',
  attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
  next_attempt_at DATETIME(3) NULL,
  lease_token CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_expires_at DATETIME(3) NULL,
  last_error_code VARCHAR(64) NOT NULL DEFAULT '',
  row_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  occurred_at DATETIME(3) NOT NULL,
  expires_at DATETIME(3) NULL,
  processed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE INDEX uq_delivery_notification_event_public_id (event_public_id),
  UNIQUE INDEX uq_delivery_notification_event_version (aggregate_type, aggregate_public_id, aggregate_version, event_type),
  INDEX idx_delivery_notification_event_claim (status, next_attempt_at, lease_expires_at, id),
  CONSTRAINT chk_delivery_notification_event_status CHECK (status IN ('pending', 'processing', 'retry_wait', 'expanded', 'skipped', 'deadletter')),
  CONSTRAINT chk_delivery_notification_event_version CHECK (aggregate_version > 0 AND payload_version > 0 AND row_version > 0),
  CONSTRAINT chk_delivery_notification_event_lease CHECK ((status = 'processing' AND lease_token IS NOT NULL AND lease_expires_at IS NOT NULL) OR (status <> 'processing' AND lease_token IS NULL AND lease_expires_at IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS delivery_notification_inbox (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  inbox_public_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  event_public_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  recipient_user_id BIGINT UNSIGNED NOT NULL,
  purpose VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  title VARCHAR(128) NOT NULL,
  summary VARCHAR(256) NOT NULL,
  aggregate_type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  aggregate_public_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
  aggregate_version BIGINT UNSIGNED NOT NULL,
  target_path VARCHAR(256) NOT NULL DEFAULT '',
  status VARCHAR(24) NOT NULL DEFAULT 'pending',
  delivered_at DATETIME(3) NULL,
  read_at DATETIME(3) NULL,
  row_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE INDEX uq_delivery_notification_inbox_public_id (inbox_public_id),
  UNIQUE INDEX uq_delivery_notification_inbox_coordinate (event_public_id, recipient_user_id, purpose),
  INDEX idx_delivery_notification_inbox_recipient (recipient_user_id, status, read_at, created_at, id),
  CONSTRAINT chk_delivery_notification_inbox_status CHECK (status IN ('pending', 'delivered', 'read', 'skipped')),
  CONSTRAINT chk_delivery_notification_inbox_identity CHECK (recipient_user_id > 0 AND aggregate_version > 0 AND row_version > 0),
  CONSTRAINT chk_delivery_notification_inbox_read CHECK ((status = 'read' AND read_at IS NOT NULL) OR (status <> 'read' AND read_at IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS delivery_notification_deliveries (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  delivery_public_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  event_public_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  recipient_user_id BIGINT UNSIGNED NOT NULL,
