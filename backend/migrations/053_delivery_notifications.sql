  purpose VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  template_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
  template_snapshot JSON NOT NULL,
  payload_version INT UNSIGNED NOT NULL DEFAULT 1,
  status VARCHAR(24) NOT NULL DEFAULT 'pending',
  attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
  next_attempt_at DATETIME(3) NULL,
  lease_token CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_expires_at DATETIME(3) NULL,
  subscription_id BIGINT UNSIGNED NULL,
  subscription_nonce VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  provider_message_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL DEFAULT '',
  last_error_code VARCHAR(64) NOT NULL DEFAULT '',
  last_error VARCHAR(256) NOT NULL DEFAULT '',
  row_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  expires_at DATETIME(3) NULL,
  processed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE INDEX uq_delivery_notification_delivery_public_id (delivery_public_id),
  UNIQUE INDEX uq_delivery_notification_delivery_coordinate (event_public_id, recipient_user_id, channel, purpose),
  INDEX idx_delivery_notification_delivery_claim (status, next_attempt_at, lease_expires_at, id),
  INDEX idx_delivery_notification_delivery_channel_claim (channel, status, next_attempt_at, lease_expires_at, id),
  INDEX idx_delivery_notification_delivery_recipient (recipient_user_id, channel, status, id),
  CONSTRAINT chk_delivery_notification_delivery_channel CHECK (channel IN ('in_app', 'wechat_subscribe', 'wecom')),
  CONSTRAINT chk_delivery_notification_delivery_status CHECK (status IN ('pending', 'processing', 'accepted', 'delivered', 'read', 'unknown', 'retry_wait', 'blocked', 'skipped', 'deadletter')),
  CONSTRAINT chk_delivery_notification_delivery_identity CHECK (recipient_user_id > 0 AND payload_version > 0 AND row_version > 0),
  CONSTRAINT chk_delivery_notification_delivery_lease CHECK ((status = 'processing' AND lease_token IS NOT NULL AND lease_expires_at IS NOT NULL) OR (status <> 'processing' AND lease_token IS NULL AND lease_expires_at IS NULL)),
  CONSTRAINT chk_delivery_notification_delivery_subscription CHECK ((subscription_id IS NULL AND subscription_nonce IS NULL) OR (subscription_id IS NOT NULL AND subscription_nonce IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS notification_subscriptions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  app_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  openid VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  template_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  authorization_nonce VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(24) NOT NULL,
  remaining_quota INT UNSIGNED NOT NULL DEFAULT 0,
  reserved_quota INT UNSIGNED NOT NULL DEFAULT 0,
  reservation_nonce VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  authorized_at DATETIME(3) NOT NULL,
  reserved_at DATETIME(3) NULL,
  expires_at DATETIME(3) NULL,
  invalidated_at DATETIME(3) NULL,
  invalidation_reason VARCHAR(64) NOT NULL DEFAULT '',
  row_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE INDEX uq_notification_subscription_authorization (user_id, app_id, template_key, authorization_nonce),
  UNIQUE INDEX uq_notification_subscription_reservation (user_id, app_id, template_key, reservation_nonce),
  INDEX idx_notification_subscription_available (user_id, app_id, template_key, status, remaining_quota, id),
  CONSTRAINT chk_notification_subscription_status CHECK (status IN ('accepted', 'rejected', 'banned', 'closed', 'revoked', 'invalid', 'exhausted')),
  CONSTRAINT chk_notification_subscription_identity CHECK (user_id > 0 AND row_version > 0 AND CHAR_LENGTH(openid) > 0),
  CONSTRAINT chk_notification_subscription_quota CHECK (remaining_quota + reserved_quota <= 1 AND (status = 'accepted' OR remaining_quota = 0)),
  CONSTRAINT chk_notification_subscription_reservation CHECK ((reservation_nonce IS NULL AND reserved_quota = 0 AND reserved_at IS NULL) OR (reservation_nonce IS NOT NULL AND reserved_quota = 1 AND reserved_at IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS im_notification_receipts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  sdk_app_id BIGINT UNSIGNED NOT NULL,
  provider_message_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
  sender_account VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  recipient_account VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  sender_user_id BIGINT UNSIGNED NOT NULL,
  recipient_user_id BIGINT UNSIGNED NOT NULL,
  callback_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  conversation_type VARCHAR(16) NOT NULL,
  conversation_public_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL DEFAULT '',
  status VARCHAR(24) NOT NULL DEFAULT 'received',
  occurred_at DATETIME(3) NOT NULL,
  created_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE INDEX uq_im_notification_receipt_message (sdk_app_id, provider_message_id, sender_account, recipient_account),
  INDEX idx_im_notification_receipt_recipient (recipient_user_id, occurred_at, id),
  CONSTRAINT chk_im_notification_receipt_status CHECK (status IN ('received', 'processed', 'skipped')),
  CONSTRAINT chk_im_notification_receipt_conversation CHECK (conversation_type IN ('c2c', 'group')),
  CONSTRAINT chk_im_notification_receipt_identity CHECK (sdk_app_id > 0 AND sender_user_id > 0 AND recipient_user_id > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
