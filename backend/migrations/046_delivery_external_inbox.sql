-- Durable normalized events only; no webhook, shop connection or payment switch.
-- Additive/repeatable. Keep this table when rolling application code back.
CREATE TABLE IF NOT EXISTS delivery_external_inbox (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  binding_key VARCHAR(64) COLLATE utf8mb4_0900_bin NOT NULL,
  merchant_user_id BIGINT UNSIGNED NOT NULL,
  platform VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  shop_id VARCHAR(64) COLLATE utf8mb4_0900_bin NOT NULL,
  source_order_id VARCHAR(128) COLLATE utf8mb4_0900_bin NOT NULL,
  event_id VARCHAR(128) COLLATE utf8mb4_0900_bin NOT NULL,
  event_type VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  occurred_at DATETIME(6) NOT NULL,
  payload JSON NOT NULL,
  fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
  attempts INT UNSIGNED NOT NULL DEFAULT 0,
  lease_token CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_expires_at DATETIME(6) NULL,
  next_attempt_at DATETIME(6) NULL,
  order_public_id VARCHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
  reason VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_delivery_external_event (platform, shop_id, event_id),
  UNIQUE KEY uq_delivery_external_request (request_id),
  KEY idx_delivery_external_claim (status, next_attempt_at, lease_expires_at, id),
  KEY idx_delivery_external_source (platform, shop_id, source_order_id),
  KEY idx_delivery_external_merchant (merchant_user_id, id),
  CONSTRAINT chk_delivery_external_platform CHECK (platform IN ('taobao','jd','meituan')),
  CONSTRAINT chk_delivery_external_type CHECK (event_type IN ('created','updated','cancelled')),
  CONSTRAINT chk_delivery_external_status CHECK (status IN ('pending','processing','retry_wait','created','reused','needs_review','deadletter')),
  CONSTRAINT chk_delivery_external_identity CHECK (merchant_user_id > 0 AND CHAR_LENGTH(TRIM(shop_id)) > 0 AND CHAR_LENGTH(TRIM(source_order_id)) > 0 AND CHAR_LENGTH(TRIM(event_id)) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
