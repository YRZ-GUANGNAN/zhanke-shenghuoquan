const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const root = path.resolve(__dirname, '..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const source = read('apps/miniapp/src/services/campus-info-model.ts')
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText
const model = {}
new Function('exports', output)(model)
const guides = JSON.parse(read('backend/internal/module/campusinfo/content.json'))
assert.equal(model.parseCampusGuides({items: guides}).length, 5)
assert.deepEqual(model.parseCampusGuides({items: []}), [])
for (const malformed of [null, {}, {items: [guides[0], guides[0]]}, {items: [{...guides[0], sections: []}]}, {items: [{...guides[0], sourceUrl: 'https://evil.example/' }]}]) assert.equal(model.parseCampusGuides(malformed), null)
for (const id of ['1', '', '../library-hours', 'library-hours?token=x', '%6cibrary-hours', 'library-hours#x', null]) assert.equal(model.validGuideId(id), false)
for (const guide of guides) assert.equal(model.validGuideId(guide.id), true)
require('./lib/campus-info-contract.cjs').assertCampusInfoHome(read('apps/miniapp/src/pages/home/index.tsx'))
const main = read('backend/cmd/server/main.go')
assert.match(main, /featureflags\.RestrictToCampusInfo\(\)/)
assert.match(main, /campusGuides\.Register\(api\)/)
assert.doesNotMatch(read('backend/internal/module/featureflags/release.go'), /os\.Getenv|LookupEnv/)
assert.match(read('apps/admin/src/FeaturePolicyConsole.tsx'), /!releaseRestricted/)
console.log('Campus info: real published content, schema, source allowlist, safe IDs and fixed release scope PASS')
