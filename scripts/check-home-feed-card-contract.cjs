const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const pageRoot = path.join(root, 'apps', 'miniapp', 'src', 'pages', 'home')
const source = fs.readFileSync(path.join(pageRoot, 'index.tsx'), 'utf8')
const style = fs.readFileSync(path.join(pageRoot, 'index.scss'), 'utf8')

assert.match(source, /kind:\s*'post'\s*\|\s*'product'/, 'feed cards must distinguish posts from products')
assert.match(source, /const cardColumns = useMemo\(\(\) => splitCards\(cards\), \[cards\]\)/, 'all discover cards must preserve one shared grid order')
assert.match(source, /const rowIndex = Math\.floor\(index \/ 2\)/, 'the shared grid must mix content types across both columns by row')
assert.match(source, /rowIndex % 2 === 0 \? columnIndex === 0 : columnIndex === 1/, 'successive rows must reverse column placement to avoid type columns')
assert.match(source, /student-media-grid/, 'posts and products must use the same stable media grid')
assert.match(source, /renderDiscoverCard/, 'all discover content must share one card renderer')
assert.match(source, /student-media-card--no-image/, 'image-free content must use the shared honest no-image variant')
assert.match(source, /failedImageKeys\.has\(imageKey\)/, 'failed media must fall back to an honest no-image state')
assert.match(source, /const imageKey = `\$\{cardKey\}:\$\{card\.imageUrl \|\| 'no-image'\}`/, 'changed image URLs must receive a fresh failure-retry key')
assert.match(source, /priceLabel:\s*`¥\$\{product\.price\}`/, 'product cards must preserve the real product price')
assert.match(source, /student-media-card__support--\$\{card\.kind\}/, 'posts and products must share one stable supporting-information slot')
assert.match(source, /card\.kind === 'product' \? 'star' : 'heart'/, 'products must use the established favorite-star language')
assert.doesNotMatch(source, /student-text-stream|student-text-card/, 'discover content must not split image-free posts into a separate layout')
assert.doesNotMatch(source, /const heights:/, 'feed cards must not use randomized heights')
assert.doesNotMatch(source, /student-post-card__media--\$\{card\.height\}/, 'media regions must not bind randomized heights')
assert.doesNotMatch(style, /\$placeholder-stripe/, 'the home feed must not render striped fake media')
assert.match(style, /aspect-ratio:\s*4\s*\/\s*3/, 'discover cards must use a compact stable 4:3 media ratio')
assert.match(style, /\.student-discover-content\s*\{[^}]*padding-bottom:\s*calc\([^;]*env\(safe-area-inset-bottom\)/s, 'all feed and feedback states must clear the fixed navigation and device safe area')
assert.doesNotMatch(style, /\.student-text-card/, 'the old full-width text-card system must be removed')

console.log('home feed card contract: ok')
