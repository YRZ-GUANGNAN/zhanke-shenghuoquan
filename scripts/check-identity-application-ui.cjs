const assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path')
const root = path.resolve(__dirname, '../apps/miniapp/src')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const page = read('pages/identity-application/index.tsx')
const modal = read('components/IdentityApplicationEntryModal.tsx')
const summary = read('components/identity-application-summary.tsx')
const profile = read('pages/profile/index.tsx')
assert.match(modal, /<AppDialog/)
assert.doesNotMatch(modal, /submitIdentityApplication|switchIdentity|resolveMedia|Taro\.showModal/)
assert.doesNotMatch(page, /resolveMedia|waitForMediaApproval|Taro\.showModal/)
assert.match(page, /status\.purpose === 'identity_application' && isMediaUsable\(status\)/)
assert.match(page, /<IdentityApplicationContent key=\{accountScope\}/)
assert.match(profile, /availability\?\.status === 'pending'/)
assert.match(profile, /availability\?\.status === 'rejected'/)
assert.match(profile, /if \(!visibility\.identity_application\)/)
assert.match(summary, /applicationTime\(application\.submittedAt\)/)
assert.match(summary, /applicationTime\(application\.reviewedAt\)/)
assert.doesNotMatch(summary, /application\.events|预计\d|保证通过/)
const pageStyle = read('pages/identity-application/index.scss')
assert.match(pageStyle, /env\(safe-area-inset-bottom\)/)
assert.match(pageStyle, /min-height: 44PX/)
for (const file of ['pages/identity-application/index.scss','components/IdentityApplicationEntryModal.scss','components/identity-application-summary.scss']) {
  const style = read(file)
  assert.doesNotMatch(style, /^\s*(page|:root|\*)\s*\{/m, `${file} 不得修改全局样式`)
  assert.doesNotMatch(style, /\$gradient-primary|placeholder-stripe|rotate\(360deg\)/)
  assert.match(style, /prefers-reduced-motion/)
}
console.log('identity application UI boundaries: ok')
